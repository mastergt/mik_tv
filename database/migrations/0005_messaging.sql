BEGIN;

CREATE TABLE messaging.messages (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  provider_id integer REFERENCES core.providers(id) ON DELETE RESTRICT,
  title text,
  body text NOT NULL CHECK (btrim(body) <> ''),
  image_key text,
  display_type text NOT NULL CHECK (display_type IN ('popup', 'ticker', 'banner', 'system')),
  priority smallint NOT NULL DEFAULT 5 CHECK (priority BETWEEN 1 AND 10),
  duration_seconds integer CHECK (duration_seconds IS NULL OR duration_seconds > 0),
  ticker_speed smallint CHECK (ticker_speed IS NULL OR ticker_speed BETWEEN 1 AND 10),
  requires_ack boolean NOT NULL DEFAULT false,
  status text NOT NULL DEFAULT 'draft' CHECK (status IN ('draft', 'active', 'archived')),
  enabled boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  created_by bigint REFERENCES auth.users(id) ON DELETE SET NULL,
  updated_by bigint REFERENCES auth.users(id) ON DELETE SET NULL
);
COMMENT ON COLUMN messaging.messages.provider_id IS 'Owner provider; NULL = system/global campaign. Recipient provider filtering is configured separately.';
CREATE INDEX messaging_messages_provider_idx ON messaging.messages(provider_id, created_at DESC);
CREATE INDEX messaging_messages_status_idx ON messaging.messages(status, enabled);

CREATE TABLE messaging.audiences (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  message_id bigint NOT NULL REFERENCES messaging.messages(id) ON DELETE CASCADE,
  rules jsonb NOT NULL CHECK (jsonb_typeof(rules) = 'object'),
  created_at timestamptz NOT NULL DEFAULT now()
);
COMMENT ON COLUMN messaging.audiences.rules IS 'Validated declarative filter AST, not SQL. Supports providers, abonents, terminals, playlists, balance_lt_kopecks, online_only, platforms; combined with AND/OR in backend';
CREATE INDEX messaging_audiences_message_idx ON messaging.audiences(message_id);

CREATE TABLE messaging.templates (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  provider_id integer REFERENCES core.providers(id) ON DELETE CASCADE,
  name text NOT NULL,
  display_type text NOT NULL CHECK (display_type IN ('popup', 'ticker', 'banner', 'system')),
  title text,
  body text NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE messaging.schedules (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  message_id bigint NOT NULL REFERENCES messaging.messages(id) ON DELETE CASCADE,
  run_at timestamptz,
  cron_expression text,
  timezone text NOT NULL DEFAULT 'Europe/Moscow',
  starts_at timestamptz,
  ends_at timestamptz,
  next_run_at timestamptz,
  enabled boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT now(),
  CHECK ((run_at IS NOT NULL AND cron_expression IS NULL) OR (run_at IS NULL AND cron_expression IS NOT NULL)),
  CHECK (ends_at IS NULL OR starts_at IS NULL OR ends_at > starts_at)
);
CREATE INDEX messaging_schedules_ready_idx ON messaging.schedules(next_run_at) WHERE enabled;

CREATE TABLE messaging.dispatches (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  message_id bigint NOT NULL REFERENCES messaging.messages(id) ON DELETE RESTRICT,
  schedule_id bigint REFERENCES messaging.schedules(id) ON DELETE SET NULL,
  scheduled_for timestamptz NOT NULL DEFAULT now(),
  status text NOT NULL DEFAULT 'queued' CHECK (status IN ('queued', 'running', 'completed', 'failed')),
  matched_recipients integer CHECK (matched_recipients IS NULL OR matched_recipients >= 0),
  started_at timestamptz,
  finished_at timestamptz,
  error_message text,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX messaging_dispatches_schedule_uq ON messaging.dispatches(schedule_id, scheduled_for) WHERE schedule_id IS NOT NULL;
CREATE INDEX messaging_dispatches_ready_idx ON messaging.dispatches(status, created_at);
CREATE INDEX messaging_dispatches_message_idx ON messaging.dispatches(message_id, created_at DESC);

CREATE TABLE messaging.deliveries (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  dispatch_id bigint NOT NULL REFERENCES messaging.dispatches(id) ON DELETE CASCADE,
  abonent_id bigint REFERENCES subscribers.abonents(id) ON DELETE SET NULL,
  terminal_id bigint REFERENCES subscribers.terminals(id) ON DELETE SET NULL,
  status text NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'sent', 'shown', 'acknowledged', 'failed', 'expired')),
  created_at timestamptz NOT NULL DEFAULT now(),
  sent_at timestamptz,
  shown_at timestamptz,
  acknowledged_at timestamptz,
  last_error text,
  CHECK (abonent_id IS NOT NULL OR terminal_id IS NOT NULL)
);
CREATE UNIQUE INDEX messaging_delivery_per_terminal_uq ON messaging.deliveries(dispatch_id, terminal_id) WHERE terminal_id IS NOT NULL;
CREATE UNIQUE INDEX messaging_delivery_per_abonent_uq ON messaging.deliveries(dispatch_id, abonent_id) WHERE terminal_id IS NULL AND abonent_id IS NOT NULL;
CREATE INDEX messaging_deliveries_terminal_pending_idx ON messaging.deliveries(terminal_id, created_at DESC) WHERE status IN ('pending', 'sent');
CREATE INDEX messaging_deliveries_abonent_pending_idx ON messaging.deliveries(abonent_id, created_at DESC) WHERE status IN ('pending', 'sent');


-- Keep modified timestamps server-controlled.
CREATE TRIGGER messaging_messages_touch BEFORE UPDATE ON messaging.messages FOR EACH ROW EXECUTE FUNCTION core.touch_updated_at();

INSERT INTO core.schema_migrations(version) VALUES ('0005_messaging');
COMMIT;
