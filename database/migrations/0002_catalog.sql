BEGIN;

CREATE TABLE catalog.app_types (
  id smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code text NOT NULL UNIQUE CHECK (code ~ '^[a-z][a-z0-9_]*$'),
  name text NOT NULL,
  ui_config jsonb NOT NULL DEFAULT '{}'::jsonb CHECK (jsonb_typeof(ui_config) = 'object'),
  enabled boolean NOT NULL DEFAULT true
);
COMMENT ON TABLE catalog.app_types IS 'Application modes: tv, cctv, intercom, radio, etc. A stream has one primary mode';

CREATE TABLE catalog.genres (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text NOT NULL CHECK (btrim(name) <> ''),
  visibility text NOT NULL DEFAULT 'all' CHECK (visibility IN ('all', 'selected')),
  is_adult boolean NOT NULL DEFAULT false,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  created_by bigint REFERENCES auth.users(id) ON DELETE SET NULL,
  updated_by bigint REFERENCES auth.users(id) ON DELETE SET NULL
);
CREATE UNIQUE INDEX catalog_genres_name_ci_idx ON catalog.genres(lower(name));
CREATE TABLE catalog.genre_providers (
  genre_id integer NOT NULL REFERENCES catalog.genres(id) ON DELETE CASCADE,
  provider_id integer NOT NULL REFERENCES core.providers(id) ON DELETE CASCADE,
  PRIMARY KEY (genre_id, provider_id)
);
CREATE INDEX catalog_genre_providers_provider_idx ON catalog.genre_providers(provider_id);

CREATE TABLE catalog.streams (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  number integer NOT NULL CHECK (number > 0),
  name text NOT NULL CHECK (btrim(name) <> ''),
  description text,
  app_type_id smallint NOT NULL REFERENCES catalog.app_types(id),
  logo_key text,
  visibility text NOT NULL DEFAULT 'all' CHECK (visibility IN ('all', 'selected')),
  is_public boolean NOT NULL DEFAULT false,
  is_adult boolean NOT NULL DEFAULT false,
  age_rating smallint NOT NULL DEFAULT 0 CHECK (age_rating BETWEEN 0 AND 21),
  is_radio boolean NOT NULL DEFAULT false,
  enabled boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  created_by bigint REFERENCES auth.users(id) ON DELETE SET NULL,
  updated_by bigint REFERENCES auth.users(id) ON DELETE SET NULL
);
CREATE INDEX catalog_streams_list_idx ON catalog.streams(app_type_id, enabled, number, id);
CREATE INDEX catalog_streams_name_ci_idx ON catalog.streams(lower(name));
CREATE INDEX catalog_streams_public_idx ON catalog.streams(number, id) WHERE enabled AND is_public;

CREATE TABLE catalog.stream_providers (
  stream_id bigint NOT NULL REFERENCES catalog.streams(id) ON DELETE CASCADE,
  provider_id integer NOT NULL REFERENCES core.providers(id) ON DELETE CASCADE,
  PRIMARY KEY (stream_id, provider_id)
);
CREATE INDEX catalog_stream_providers_provider_idx ON catalog.stream_providers(provider_id, stream_id);
COMMENT ON TABLE catalog.stream_providers IS 'Used when streams.visibility=selected. Empty selected list means visible to none (fail closed).';

CREATE TABLE catalog.stream_genres (
  stream_id bigint NOT NULL REFERENCES catalog.streams(id) ON DELETE CASCADE,
  genre_id integer NOT NULL REFERENCES catalog.genres(id) ON DELETE CASCADE,
  PRIMARY KEY (stream_id, genre_id)
);
CREATE INDEX catalog_stream_genres_genre_idx ON catalog.stream_genres(genre_id, stream_id);

CREATE TABLE catalog.stream_provider_overrides (
  stream_id bigint NOT NULL REFERENCES catalog.streams(id) ON DELETE CASCADE,
  provider_id integer NOT NULL REFERENCES core.providers(id) ON DELETE CASCADE,
  number_override integer CHECK (number_override > 0),
  name_override text CHECK (name_override IS NULL OR btrim(name_override) <> ''),
  logo_key_override text,
  enabled_override boolean,
  updated_at timestamptz NOT NULL DEFAULT now(),
  updated_by bigint REFERENCES auth.users(id) ON DELETE SET NULL,
  PRIMARY KEY (stream_id, provider_id)
);
CREATE INDEX catalog_stream_overrides_provider_idx ON catalog.stream_provider_overrides(provider_id, stream_id);

CREATE TABLE catalog.stream_sources (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  stream_id bigint NOT NULL REFERENCES catalog.streams(id) ON DELETE CASCADE,
  provider_id integer REFERENCES core.providers(id) ON DELETE CASCADE,
  source_kind text NOT NULL CHECK (source_kind IN ('live', 'dvr')),
  protocol text NOT NULL CHECK (protocol IN ('hls', 'udp', 'http_ts', 'dash', 'rtsp', 'other')),
  url text NOT NULL CHECK (url ~* '^[a-z][a-z0-9+.-]*://.+'),
  priority integer NOT NULL DEFAULT 10 CHECK (priority > 0),
  enabled boolean NOT NULL DEFAULT true,
  dvr_url_mode text CHECK (dvr_url_mode IN ('template', 'api')),
  dvr_config jsonb NOT NULL DEFAULT '{}'::jsonb CHECK (jsonb_typeof(dvr_config) = 'object'),
  dvr_window_seconds integer CHECK (dvr_window_seconds IS NULL OR dvr_window_seconds > 0),
  comment text,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  created_by bigint REFERENCES auth.users(id) ON DELETE SET NULL,
  updated_by bigint REFERENCES auth.users(id) ON DELETE SET NULL,
  CHECK ((source_kind = 'live' AND dvr_url_mode IS NULL AND dvr_window_seconds IS NULL)
      OR (source_kind = 'dvr' AND dvr_url_mode IS NOT NULL))
);
COMMENT ON COLUMN catalog.stream_sources.priority IS 'Lower = preferred: 10 main, 20 reserve. Provider-specific sources are preferred to global sources.';
COMMENT ON COLUMN catalog.stream_sources.url IS 'For DVR/template may include {start_unix}, {end_unix}, {duration_sec}, {start_iso}, {end_iso}; validate/expand only in backend';
CREATE UNIQUE INDEX catalog_source_global_priority_uq ON catalog.stream_sources(stream_id, source_kind, priority) WHERE provider_id IS NULL;
CREATE UNIQUE INDEX catalog_source_provider_priority_uq ON catalog.stream_sources(stream_id, provider_id, source_kind, priority) WHERE provider_id IS NOT NULL;
CREATE INDEX catalog_sources_list_idx ON catalog.stream_sources(stream_id, source_kind, enabled, priority);
CREATE INDEX catalog_sources_provider_idx ON catalog.stream_sources(provider_id, stream_id) WHERE provider_id IS NOT NULL;

CREATE TABLE catalog.source_health (
  source_id bigint PRIMARY KEY REFERENCES catalog.stream_sources(id) ON DELETE CASCADE,
  status text NOT NULL DEFAULT 'unknown' CHECK (status IN ('unknown', 'healthy', 'degraded', 'down')),
  last_checked_at timestamptz,
  last_healthy_at timestamptz,
  response_time_ms integer CHECK (response_time_ms IS NULL OR response_time_ms >= 0),
  consecutive_failures integer NOT NULL DEFAULT 0 CHECK (consecutive_failures >= 0),
  last_error text,
  updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX catalog_source_health_status_idx ON catalog.source_health(status, last_checked_at);
CREATE TABLE catalog.source_health_events (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  source_id bigint NOT NULL REFERENCES catalog.stream_sources(id) ON DELETE CASCADE,
  old_status text CHECK (old_status IN ('unknown', 'healthy', 'degraded', 'down')),
  new_status text NOT NULL CHECK (new_status IN ('unknown', 'healthy', 'degraded', 'down')),
  reason text,
  occurred_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX catalog_source_health_events_idx ON catalog.source_health_events(source_id, occurred_at DESC);

CREATE TABLE catalog.playlists (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text NOT NULL CHECK (btrim(name) <> ''),
  description text,
  visibility text NOT NULL DEFAULT 'all' CHECK (visibility IN ('all', 'selected')),
  is_public boolean NOT NULL DEFAULT false,
  is_hidden boolean NOT NULL DEFAULT false,
  enabled boolean NOT NULL DEFAULT true,
  expires_at timestamptz,
  price_kopecks bigint CHECK (price_kopecks IS NULL OR price_kopecks >= 0),
  currency char(3) NOT NULL DEFAULT 'RUB' CHECK (currency ~ '^[A-Z]{3}$'),
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  created_by bigint REFERENCES auth.users(id) ON DELETE SET NULL,
  updated_by bigint REFERENCES auth.users(id) ON DELETE SET NULL
);
CREATE INDEX catalog_playlists_visible_idx ON catalog.playlists(visibility, enabled);
CREATE INDEX catalog_playlists_name_ci_idx ON catalog.playlists(lower(name));

CREATE TABLE catalog.playlist_providers (
  playlist_id bigint NOT NULL REFERENCES catalog.playlists(id) ON DELETE CASCADE,
  provider_id integer NOT NULL REFERENCES core.providers(id) ON DELETE CASCADE,
  PRIMARY KEY (playlist_id, provider_id)
);
CREATE INDEX catalog_playlist_providers_provider_idx ON catalog.playlist_providers(provider_id, playlist_id);

CREATE TABLE catalog.playlist_streams (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  playlist_id bigint NOT NULL REFERENCES catalog.playlists(id) ON DELETE CASCADE,
  stream_id bigint NOT NULL REFERENCES catalog.streams(id) ON DELETE RESTRICT,
  position integer NOT NULL CHECK (position > 0),
  enabled boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  updated_by bigint REFERENCES auth.users(id) ON DELETE SET NULL,
  UNIQUE (playlist_id, stream_id),
  CONSTRAINT playlist_streams_position_uq UNIQUE (playlist_id, position) DEFERRABLE INITIALLY IMMEDIATE
);
CREATE INDEX catalog_playlist_streams_stream_idx ON catalog.playlist_streams(stream_id);

CREATE FUNCTION catalog.stream_visible_to_provider(p_stream_id bigint, p_provider_id integer)
RETURNS boolean LANGUAGE sql STABLE AS $$
  SELECT EXISTS (
    SELECT 1 FROM catalog.streams s
    WHERE s.id = p_stream_id
      AND (s.visibility = 'all' OR EXISTS (
        SELECT 1 FROM catalog.stream_providers sp
        WHERE sp.stream_id = s.id AND sp.provider_id = p_provider_id
      ))
  );
$$;

CREATE FUNCTION catalog.playlist_visible_to_provider(p_playlist_id bigint, p_provider_id integer)
RETURNS boolean LANGUAGE sql STABLE AS $$
  SELECT EXISTS (
    SELECT 1 FROM catalog.playlists p
    WHERE p.id = p_playlist_id
      AND (p.visibility = 'all' OR EXISTS (
        SELECT 1 FROM catalog.playlist_providers pp
        WHERE pp.playlist_id = p.id AND pp.provider_id = p_provider_id
      ))
  );
$$;


-- Keep modified timestamps server-controlled.
CREATE TRIGGER catalog_genres_touch BEFORE UPDATE ON catalog.genres FOR EACH ROW EXECUTE FUNCTION core.touch_updated_at();
CREATE TRIGGER catalog_streams_touch BEFORE UPDATE ON catalog.streams FOR EACH ROW EXECUTE FUNCTION core.touch_updated_at();
CREATE TRIGGER catalog_stream_provider_overrides_touch BEFORE UPDATE ON catalog.stream_provider_overrides FOR EACH ROW EXECUTE FUNCTION core.touch_updated_at();
CREATE TRIGGER catalog_stream_sources_touch BEFORE UPDATE ON catalog.stream_sources FOR EACH ROW EXECUTE FUNCTION core.touch_updated_at();
CREATE TRIGGER catalog_source_health_touch BEFORE UPDATE ON catalog.source_health FOR EACH ROW EXECUTE FUNCTION core.touch_updated_at();
CREATE TRIGGER catalog_playlists_touch BEFORE UPDATE ON catalog.playlists FOR EACH ROW EXECUTE FUNCTION core.touch_updated_at();
CREATE TRIGGER catalog_playlist_streams_touch BEFORE UPDATE ON catalog.playlist_streams FOR EACH ROW EXECUTE FUNCTION core.touch_updated_at();

INSERT INTO core.schema_migrations(version) VALUES ('0002_catalog');
COMMIT;
