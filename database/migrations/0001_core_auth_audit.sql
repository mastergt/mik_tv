BEGIN;

CREATE SCHEMA core;
CREATE SCHEMA auth;
CREATE SCHEMA catalog;
CREATE SCHEMA subscribers;
CREATE SCHEMA epg;
CREATE SCHEMA messaging;
CREATE SCHEMA support;
CREATE SCHEMA vod;
CREATE SCHEMA audit;

CREATE TABLE core.schema_migrations (
  version text PRIMARY KEY,
  applied_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE core.installation (
  singleton boolean PRIMARY KEY DEFAULT true CHECK (singleton),
  installation_id uuid NOT NULL UNIQUE DEFAULT gen_random_uuid(),
  name text NOT NULL DEFAULT 'IPTV Local',
  api_base_url text,
  created_at timestamptz NOT NULL DEFAULT now()
);
INSERT INTO core.installation(singleton) VALUES (true);

CREATE TABLE core.providers (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text NOT NULL UNIQUE CHECK (btrim(name) <> ''),
  slug text NOT NULL UNIQUE CHECK (slug ~ '^[a-z0-9][a-z0-9_-]*$'),
  enabled boolean NOT NULL DEFAULT true,
  timezone text NOT NULL DEFAULT 'Europe/Moscow',
  default_terminal_limit integer NOT NULL DEFAULT 3 CHECK (default_terminal_limit >= 0),
  default_concurrent_stream_limit integer NOT NULL DEFAULT 2 CHECK (default_concurrent_stream_limit >= 0),
  playback_history_enabled boolean NOT NULL DEFAULT false,
  stream_monitoring_enabled boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  created_by bigint,
  updated_by bigint
);
COMMENT ON COLUMN core.providers.default_terminal_limit IS '0 = unlimited; positive integer = active bound terminals maximum';
COMMENT ON COLUMN core.providers.default_concurrent_stream_limit IS '0 = unlimited; runtime enforcement uses short-lived playback leases';
COMMENT ON COLUMN core.providers.playback_history_enabled IS 'False disables detailed PostgreSQL playback history, not ephemeral concurrency leases';

CREATE TABLE core.system_settings (
  key text PRIMARY KEY,
  value jsonb NOT NULL,
  updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE core.provider_settings (
  provider_id integer NOT NULL REFERENCES core.providers(id) ON DELETE CASCADE,
  key text NOT NULL,
  value jsonb NOT NULL,
  updated_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (provider_id, key)
);

CREATE TABLE auth.users (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username text UNIQUE,
  password_hash text,
  display_name text NOT NULL,
  email text,
  status text NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'active', 'disabled')),
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  last_login_at timestamptz,
  CHECK (username IS NULL OR btrim(username) <> ''),
  CHECK (password_hash IS NULL OR username IS NOT NULL)
);
CREATE UNIQUE INDEX auth_users_username_ci_idx ON auth.users(lower(username)) WHERE username IS NOT NULL;
CREATE INDEX auth_users_status_idx ON auth.users(status);

ALTER TABLE core.providers
  ADD CONSTRAINT core_providers_created_by_fk FOREIGN KEY (created_by) REFERENCES auth.users(id) ON DELETE SET NULL,
  ADD CONSTRAINT core_providers_updated_by_fk FOREIGN KEY (updated_by) REFERENCES auth.users(id) ON DELETE SET NULL;

CREATE TABLE auth.oauth_providers (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code text NOT NULL UNIQUE,
  issuer text NOT NULL UNIQUE,
  client_id text NOT NULL,
  secret_env_name text,
  enabled boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT now()
);
COMMENT ON COLUMN auth.oauth_providers.secret_env_name IS 'Environment/secret-store pointer only: never store client secrets here';
CREATE TABLE auth.external_identities (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id bigint NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  oauth_provider_id integer NOT NULL REFERENCES auth.oauth_providers(id) ON DELETE RESTRICT,
  issuer text NOT NULL,
  subject text NOT NULL,
  linked_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (issuer, subject),
  UNIQUE (user_id, oauth_provider_id)
);
CREATE INDEX auth_external_identities_user_idx ON auth.external_identities(user_id);

CREATE TABLE auth.roles (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code text NOT NULL UNIQUE,
  name text NOT NULL,
  description text,
  system_role boolean NOT NULL DEFAULT false
);
CREATE TABLE auth.permissions (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code text NOT NULL UNIQUE,
  description text
);
CREATE TABLE auth.role_permissions (
  role_id integer NOT NULL REFERENCES auth.roles(id) ON DELETE CASCADE,
  permission_id integer NOT NULL REFERENCES auth.permissions(id) ON DELETE CASCADE,
  PRIMARY KEY (role_id, permission_id)
);
CREATE TABLE auth.user_role_assignments (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id bigint NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  role_id integer NOT NULL REFERENCES auth.roles(id) ON DELETE RESTRICT,
  provider_id integer REFERENCES core.providers(id) ON DELETE CASCADE,
  granted_by bigint REFERENCES auth.users(id) ON DELETE SET NULL,
  granted_at timestamptz NOT NULL DEFAULT now()
);
COMMENT ON COLUMN auth.user_role_assignments.provider_id IS 'NULL = global scope; non-NULL = selected provider; global assignment requires elevated admin authorization';
CREATE UNIQUE INDEX auth_role_assignment_global_uq ON auth.user_role_assignments(user_id, role_id) WHERE provider_id IS NULL;
CREATE UNIQUE INDEX auth_role_assignment_provider_uq ON auth.user_role_assignments(user_id, role_id, provider_id) WHERE provider_id IS NOT NULL;
CREATE INDEX auth_role_assignment_provider_idx ON auth.user_role_assignments(provider_id, user_id);

CREATE TABLE auth.user_sessions (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id bigint NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  refresh_token_hash text NOT NULL UNIQUE,
  ip inet,
  user_agent text,
  issued_at timestamptz NOT NULL DEFAULT now(),
  expires_at timestamptz NOT NULL,
  revoked_at timestamptz,
  CHECK (expires_at > issued_at)
);
CREATE INDEX auth_user_sessions_active_idx ON auth.user_sessions(user_id, expires_at) WHERE revoked_at IS NULL;

CREATE TABLE audit.events (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  occurred_at timestamptz NOT NULL DEFAULT now(),
  actor_user_id bigint REFERENCES auth.users(id) ON DELETE SET NULL,
  actor_type text NOT NULL DEFAULT 'user' CHECK (actor_type IN ('user', 'system', 'integration')),
  provider_id integer REFERENCES core.providers(id) ON DELETE SET NULL,
  action text NOT NULL,
  entity_schema text NOT NULL,
  entity_table text NOT NULL,
  entity_id text,
  changed_fields text[] NOT NULL DEFAULT '{}'::text[],
  details jsonb NOT NULL DEFAULT '{}'::jsonb CHECK (jsonb_typeof(details) = 'object'),
  ip inet
);
CREATE INDEX audit_events_occurred_idx ON audit.events(occurred_at DESC);
CREATE INDEX audit_events_actor_idx ON audit.events(actor_user_id, occurred_at DESC);
CREATE INDEX audit_events_entity_idx ON audit.events(entity_schema, entity_table, entity_id, occurred_at DESC);
COMMENT ON TABLE audit.events IS 'Application-level audit: redact passwords, credentials, access tokens and encryption material from details';


-- Keep modified timestamps server-controlled.
CREATE FUNCTION core.touch_updated_at() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  NEW.updated_at := now();
  RETURN NEW;
END;
$$;
CREATE TRIGGER core_providers_touch BEFORE UPDATE ON core.providers FOR EACH ROW EXECUTE FUNCTION core.touch_updated_at();
CREATE TRIGGER core_system_settings_touch BEFORE UPDATE ON core.system_settings FOR EACH ROW EXECUTE FUNCTION core.touch_updated_at();
CREATE TRIGGER core_provider_settings_touch BEFORE UPDATE ON core.provider_settings FOR EACH ROW EXECUTE FUNCTION core.touch_updated_at();
CREATE TRIGGER auth_users_touch BEFORE UPDATE ON auth.users FOR EACH ROW EXECUTE FUNCTION core.touch_updated_at();

INSERT INTO core.schema_migrations(version) VALUES ('0001_core_auth_audit');
COMMIT;
