CREATE FUNCTION subscribers.enforce_terminal_limit()
RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE
  v_provider_id integer;
  v_override integer;
  v_default_limit integer;
  v_limit integer;
  v_count bigint;
BEGIN
  IF NEW.abonent_id IS NULL THEN
    RETURN NEW;
  END IF;
  -- Serializes concurrent registrations for the same abonent.
  SELECT a.provider_id, a.terminal_limit_override, p.default_terminal_limit
    INTO v_provider_id, v_override, v_default_limit
    FROM subscribers.abonents a
    JOIN core.providers p ON p.id = a.provider_id
    WHERE a.id = NEW.abonent_id FOR UPDATE OF a;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'Abonent % not found', NEW.abonent_id USING ERRCODE = '23503';
  END IF;
  IF NEW.provider_id IS NULL THEN
    NEW.provider_id := v_provider_id;
  ELSIF NEW.provider_id <> v_provider_id THEN
    RAISE EXCEPTION 'Terminal provider % differs from abonent provider %', NEW.provider_id, v_provider_id USING ERRCODE = '23514';
  END IF;
  v_limit := COALESCE(v_override, v_default_limit);
  IF NEW.enabled AND v_limit > 0 THEN
    SELECT count(*) INTO v_count
    FROM subscribers.terminals
    WHERE abonent_id = NEW.abonent_id AND enabled
      AND id IS DISTINCT FROM NEW.id;
    IF v_count >= v_limit THEN
      RAISE EXCEPTION 'Terminal limit reached: abonent %, max %', NEW.abonent_id, v_limit USING ERRCODE = '23514';
    END IF;
  END IF;
  RETURN NEW;
END;
$$;
CREATE TRIGGER enforce_terminal_limit BEFORE INSERT OR UPDATE OF abonent_id, provider_id, enabled
  ON subscribers.terminals FOR EACH ROW EXECUTE FUNCTION subscribers.enforce_terminal_limit();

