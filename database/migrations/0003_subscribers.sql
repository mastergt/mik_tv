CREATE FUNCTION subscribers.check_entitlement_provider()
RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE
  v_provider_id integer;
BEGIN
  SELECT provider_id INTO v_provider_id FROM subscribers.abonents WHERE id = NEW.abonent_id;
  IF v_provider_id IS NULL THEN
    RAISE EXCEPTION 'Abonent % not found', NEW.abonent_id USING ERRCODE = '23503';
  END IF;
  IF TG_TABLE_NAME = 'abonent_playlists' THEN
    IF NOT catalog.playlist_visible_to_provider(NEW.playlist_id, v_provider_id) THEN
      RAISE EXCEPTION 'Playlist % is not available to provider %', NEW.playlist_id, v_provider_id USING ERRCODE = '23514';
    END IF;
  ELSE
    IF NOT catalog.stream_visible_to_provider(NEW.stream_id, v_provider_id) THEN
      RAISE EXCEPTION 'Stream % is not available to provider %', NEW.stream_id, v_provider_id USING ERRCODE = '23514';
    END IF;
  END IF;
  RETURN NEW;
END;
$$;
CREATE TRIGGER check_abonent_playlist_provider BEFORE INSERT OR UPDATE OF abonent_id, playlist_id
  ON subscribers.abonent_playlists FOR EACH ROW EXECUTE FUNCTION subscribers.check_entitlement_provider();
CREATE TRIGGER check_abonent_stream_provider BEFORE INSERT OR UPDATE OF abonent_id, stream_id
  ON subscribers.abonent_streams FOR EACH ROW EXECUTE FUNCTION subscribers.check_entitlement_provider();

