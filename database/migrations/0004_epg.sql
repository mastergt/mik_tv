BEGIN;

CREATE TABLE epg.languages (
  code text PRIMARY KEY CHECK (code ~ '^[a-z]{2,3}(-[A-Za-z0-9]+)*$'),
  name text NOT NULL
);
INSERT INTO epg.languages(code, name) VALUES
  ('ru', 'Русский'), ('en', 'English'), ('und', 'Не определён');

CREATE TABLE epg.sources (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text NOT NULL,
  type text NOT NULL DEFAULT 'xmltv' CHECK (type IN ('xmltv', 'upload', 'custom')),
  download_uri text CHECK (download_uri IS NULL OR download_uri ~* '^https?://.+'),
  upload_object_key text,
  import_settings jsonb NOT NULL DEFAULT '{}'::jsonb CHECK (jsonb_typeof(import_settings) = 'object'),
  CHECK ((type = 'xmltv' AND download_uri IS NOT NULL)
      OR (type = 'upload' AND upload_object_key IS NOT NULL)
      OR (type = 'custom')),
  visibility text NOT NULL DEFAULT 'all' CHECK (visibility IN ('all', 'selected')),
  language_code text REFERENCES epg.languages(code),
  enabled boolean NOT NULL DEFAULT true,
  refresh_interval_seconds integer NOT NULL DEFAULT 21600 CHECK (refresh_interval_seconds >= 300),
  expiration_seconds integer CHECK (expiration_seconds IS NULL OR expiration_seconds > 0),
  last_download_at timestamptz,
  last_success_at timestamptz,
  last_error text,
  etag text,
  comment text,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  created_by bigint REFERENCES auth.users(id) ON DELETE SET NULL,
  updated_by bigint REFERENCES auth.users(id) ON DELETE SET NULL
);
CREATE TABLE epg.source_providers (
  source_id integer NOT NULL REFERENCES epg.sources(id) ON DELETE CASCADE,
  provider_id integer NOT NULL REFERENCES core.providers(id) ON DELETE CASCADE,
  PRIMARY KEY (source_id, provider_id)
);
CREATE INDEX epg_source_providers_provider_idx ON epg.source_providers(provider_id);

CREATE TABLE epg.channels (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  source_id integer NOT NULL REFERENCES epg.sources(id) ON DELETE CASCADE,
  external_channel_id text NOT NULL,
  display_name text,
  icon_url text,
  updated_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (source_id, external_channel_id)
);
CREATE INDEX epg_channels_name_ci_idx ON epg.channels(lower(display_name));

CREATE TABLE epg.programmes (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  epg_channel_id bigint NOT NULL REFERENCES epg.channels(id) ON DELETE CASCADE,
  starts_at timestamptz NOT NULL,
  ends_at timestamptz,
  language_code text NOT NULL DEFAULT 'und' REFERENCES epg.languages(code),
  title text,
  description text,
  age_limit smallint CHECK (age_limit IS NULL OR age_limit BETWEEN 0 AND 21),
  relevance numeric(8,5),
  updated_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (epg_channel_id, starts_at, language_code),
  CHECK (ends_at IS NULL OR ends_at > starts_at)
);
CREATE INDEX epg_programmes_timeline_idx ON epg.programmes(epg_channel_id, starts_at, ends_at);
CREATE INDEX epg_programmes_cleanup_idx ON epg.programmes(ends_at) WHERE ends_at IS NOT NULL;

CREATE TABLE epg.stream_mappings (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  stream_id bigint NOT NULL REFERENCES catalog.streams(id) ON DELETE CASCADE,
  epg_channel_id bigint NOT NULL REFERENCES epg.channels(id) ON DELETE CASCADE,
  provider_id integer REFERENCES core.providers(id) ON DELETE CASCADE,
  priority integer NOT NULL DEFAULT 10 CHECK (priority > 0),
  enabled boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX epg_stream_mapping_global_channel_uq ON epg.stream_mappings(stream_id, epg_channel_id) WHERE provider_id IS NULL;
CREATE UNIQUE INDEX epg_stream_mapping_provider_channel_uq ON epg.stream_mappings(stream_id, provider_id, epg_channel_id) WHERE provider_id IS NOT NULL;
CREATE UNIQUE INDEX epg_stream_mapping_global_priority_uq ON epg.stream_mappings(stream_id, priority) WHERE provider_id IS NULL;
CREATE UNIQUE INDEX epg_stream_mapping_provider_priority_uq ON epg.stream_mappings(stream_id, provider_id, priority) WHERE provider_id IS NOT NULL;
CREATE INDEX epg_stream_mapping_channel_idx ON epg.stream_mappings(epg_channel_id);

CREATE TABLE epg.import_jobs (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  source_id integer NOT NULL REFERENCES epg.sources(id) ON DELETE CASCADE,
  status text NOT NULL DEFAULT 'queued' CHECK (status IN ('queued', 'running', 'success', 'failed')),
  started_at timestamptz,
  completed_at timestamptz,
  channels_count integer NOT NULL DEFAULT 0 CHECK (channels_count >= 0),
  programmes_count integer NOT NULL DEFAULT 0 CHECK (programmes_count >= 0),
  error_message text,
  created_at timestamptz NOT NULL DEFAULT now(),
  CHECK (completed_at IS NULL OR started_at IS NOT NULL)
);
CREATE INDEX epg_import_jobs_source_idx ON epg.import_jobs(source_id, created_at DESC);


-- Keep modified timestamps server-controlled.
CREATE TRIGGER epg_sources_touch BEFORE UPDATE ON epg.sources FOR EACH ROW EXECUTE FUNCTION core.touch_updated_at();
CREATE TRIGGER epg_channels_touch BEFORE UPDATE ON epg.channels FOR EACH ROW EXECUTE FUNCTION core.touch_updated_at();
CREATE TRIGGER epg_programmes_touch BEFORE UPDATE ON epg.programmes FOR EACH ROW EXECUTE FUNCTION core.touch_updated_at();
CREATE TRIGGER epg_stream_mappings_touch BEFORE UPDATE ON epg.stream_mappings FOR EACH ROW EXECUTE FUNCTION core.touch_updated_at();

INSERT INTO core.schema_migrations(version) VALUES ('0004_epg');
COMMIT;
